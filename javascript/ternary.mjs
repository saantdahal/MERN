// Ternary operator
// The ternary operator is a shorthand for the if-else statement. It takes three operands and is often used as a shortcut for the if statement. The syntax is as follows:
// condition ? trueExpression : falseExpression;

let a = 10;
let b = 20;

a > b ? console.log("a is greater than b") : console.log("b is greater than a");

let age = 18;

age >= 18 ? console.log("You are young") : console.log("You are child");

